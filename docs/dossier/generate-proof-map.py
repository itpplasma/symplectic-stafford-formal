#!/usr/bin/env python3
"""Generate the dossier map and claim register from the repository proof graph."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
graph_path = ROOT / "docs/proof-graph.yaml"
raw = graph_path.read_bytes()
graph = json.loads(raw)  # JSON is a strict subset of YAML.
nodes = graph["nodes"]
by_id = {node["id"]: node for node in nodes}
assert len(by_id) == len(nodes)
expected = {(dep, node["id"]) for node in nodes for dep in node["depends_on"]}
actual = {(edge["from"], edge["to"]) for edge in graph["edges"]}
assert actual == expected, (actual - expected, expected - actual)

def tex(value):
    table = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    return "".join(table.get(char, char) for char in str(value))

out = [
    "% Generated by generate-proof-map.py; edit docs/proof-graph.yaml.",
    r"\begin{center}\hypertarget{proofmap}{}",
    r"{\Large Symplectic Stafford: proof map}\\[0.4em]",
    r"{\small LEAN: utility; LEAN-SCAFFOLD: conditional contract; NOVEL: paper candidate; GAP: open gate.}",
    r"\begin{tikzpicture}[x=1cm,y=1cm]",
]
for node in nodes:
    x, y = node["position"]
    out.append(
        rf"\node[{node['kind'].lower()}] ({node['id']}) at ({x},{y}) "
        r"{\hyperlink{claim:" + node['id'] + "}{" + node['kind']
        + r"\\" + tex(node['label']) + "}};"
    )
for edge in graph["edges"]:
    a, b = edge["from"], edge["to"]
    # Outer branches route away from the middle-column claim boxes.
    if a == "pencil":
        path = f"({a}.south) |- ([yshift=0.7cm] {b}.east) -- ({b}.east)"
    elif a == "tests":
        path = f"({a}.west) -- ++(-0.65,0) |- ({b}.north west)"
    elif a == "local" and b == "colon":
        path = f"({a}.east) -- ({b}.north west)"
    else:
        path = f"({a}) -- ({b})"
    labels = {
        ("semantics", "assembly-scaffold"): (-6.2, 19.25),
        ("ordered", "local-scaffold"): (-1.2, 19.25),
        ("local", "length"): (-5, 15.5), ("local", "colon"): (-2.2, 15.5),
        ("length", "induction"): (-3.8, 12.3),
        ("tests", "induction"): (-2.9, 13.1),
        ("pencil", "induction"): (5, 12.4),
        ("colon", "induction"): (0, 12.3),
        ("induction", "terminal"): (0, 9),
        ("terminal", "package"): (2.5, 8.0),
        ("terminal", "phasei"): (0, 6),
        ("phasei", "phaseii"): (0, 3),
        ("phaseii", "publication"): (2.5, 2),
    }
    x, y = labels[(a, b)]
    out.append(rf"\draw[edge] {path};")
    out.append(rf"\node[fill=white,inner sep=1pt,font=\tiny] at ({x},{y})"
               rf" {{{tex(edge['mechanism'])}}};")
out.extend([
    r"\end{tikzpicture}\par\smallskip",
    r"{\scriptsize Graph SHA-256: \nolinkurl{" + hashlib.sha256(raw).hexdigest() + "}}",
    r"\end{center}\clearpage",
])
(HERE / "proof-map.generated.tex").write_text("\n".join(out) + "\n")

details = [r"\section{Claim register}\label{sec:claims}"]
for node in nodes:
    details.extend([
        rf"\subsection{{{tex(node['label'])}}}\hypertarget{{claim:{node['id']}}}{{}}\backmap",
        rf"\textbf{{{node['kind']}.}} {tex(node['statement'])}",
        "",
        rf"\emph{{Source:}} {tex(node['source'])}.",
        rf"\emph{{Review:}} {tex(node['review'])}",
        "",
    ])
    if node["depends_on"]:
        details.append("Dependencies: " + ", ".join(
            rf"\hyperlink{{claim:{dep}}}{{{tex(by_id[dep]['label'])}}}"
            for dep in node["depends_on"]
        ) + ".")
    else:
        details.append("No incoming claim dependency in this graph.")
details.extend([
    "",
    "Paper statements follow the graph component at mathematical source commit",
    r"\nolinkurl{" + graph["source"]["paper_commit"] + "}.",
    "The current instruction snapshot is",
    r"\nolinkurl{" + graph["source"]["instructions_commit"] + "}.",
])
(HERE / "claim-register.generated.tex").write_text("\n".join(details) + "\n")
print("generated map and claim register from", graph_path)
